def main():
    products = load_products()
    registry = L.Registry()
    infos = {p["id"]: L.enrich(p, registry) for p in products}
    unmatched = [p for p in products if not infos[p["id"]]["set_rec"]]
    for p in unmatched:
        print(f"WARNING: '{p['id']}' set '{p['set']}' is not in seo/sets.json. Add the set (or an alias) so it gets an era.")

    pages = L.build_categories(products, infos, registry)
    template = read("product.html")
    ids = []
    for p in products:
        if not re.fullmatch(r"[a-z0-9-]+", p["id"]):
            sys.exit(f"Unsafe product id for a file name: {p['id']!r}")
        image_rel = share_image(p)
        write(f"card-{p['id']}.html", card_page(template, p, infos[p["id"]], image_rel, registry, pages))
        ids.append(p["id"])
    for pg in pages:
        write(pg["file"], category_page(pg, infos, pages))
    write(GUIDE_FILE, guide_page(registry, products, infos, pages))

    # Remove generated pages and images that no longer apply (sold-through categories, removed cards).
    keep = {f"card-{i}.html" for i in ids} | {pg["file"] for pg in pages} | {GUIDE_FILE}
    for name in os.listdir(ROOT):
        if name.endswith(".html") and name not in keep:
            with open(os.path.join(ROOT, name), encoding="utf-8") as f:
                if f.read(len(GENERATED_MARK)) == GENERATED_MARK:
                    os.remove(os.path.join(ROOT, name))
    for name in os.listdir(SHARE_DIR):
        if name.endswith(".jpg") and name[:-4] not in ids:
            os.remove(os.path.join(SHARE_DIR, name))

    html_files = sorted(n for n in os.listdir(ROOT) if n.endswith(".html"))
    fill_markers(html_files, "browse", browse_block(pages))
    fill_markers(html_files, "footer-links", footer_block(pages))

    write("card-pages.js",
          "// Generated by tools/build_card_pages.py. Cards that have their own shareable page.\n"
          f"window.GC01_CARD_PAGES = {json.dumps(sorted(ids))};\n"
          "window.gc01ProductUrl = function (id) {\n"
          "  return window.GC01_CARD_PAGES.indexOf(id) !== -1 ? \"card-\" + id + \".html\" : \"product.html?id=\" + encodeURIComponent(id);\n"
          "};\n")
    write_sitemap(products, pages)
    write_merchant_feed(products, infos, registry)
    print(f"Built {len(ids)} card pages, {len(pages)} category pages, the set guide, sitemap.xml and the Merchant feed.")
    if unmatched:
        print(f"{len(unmatched)} card(s) need their set added to seo/sets.json (see warnings above).")


if __name__ == "__main__":
    main()
