# ---------------------------------------------------------------- shell pages

def shell_parts():
    """Header and footer shared with the rest of the site, taken from about.html."""
    doc = read("about.html")
    head_end = doc.index("<main id=\"main\">")
    foot_start = doc.index('    <footer class="site-footer')
    return doc[:head_end], doc[foot_start:]


def card_tile(p, i):
    href = f"card-{p['id']}.html"
