    if parent:
        crumbs.append((parent["h1"], f"{SITE}/{parent['file']}"))
    crumbs.append((p["name"], url))
    doc = doc.replace("</head>", ld_script(product_ld) + ld_script(breadcrumb_ld(crumbs)) + "</head>", 1)

    # Visible content in the HTML itself (product.js re-renders the same values).
    crumb_html = '<a href="index.html#shop">Shop</a>'
    if parent:
        crumb_html += f' / <a href="{parent["file"]}">{esc(parent["h1"])}</a>'
