def share_image(p):
    """Card photo centred on the site's dark background with a soft blue glow."""
    card = Image.open(os.path.join(ROOT, p["image"])).convert("RGB")
    bg = Image.new("RGB", (W, H), (22, 21, 19))
    glow = Image.new("L", (W, H), 0)
    ImageDraw.Draw(glow).ellipse((W // 2 - 420, -120, W // 2 + 420, H + 120), fill=110)
    glow = glow.filter(ImageFilter.GaussianBlur(120))
    bg.paste(Image.new("RGB", (W, H), (52, 84, 214)), (0, 0), glow)
    ch = H - 60
    cw = round(card.width * ch / card.height)
    card = card.resize((cw, ch), Image.LANCZOS)
    shadow = Image.new("L", (W, H), 0)
    x, y = (W - cw) // 2, 30
    ImageDraw.Draw(shadow).rectangle((x + 10, y + 24, x + cw + 10, y + ch + 24), fill=170)
    shadow = shadow.filter(ImageFilter.GaussianBlur(22))
    bg.paste(Image.new("RGB", (W, H), (0, 0, 0)), (0, 0), shadow)
    bg.paste(card, (x, y))
    logo_path = os.path.join(ROOT, "images", "logo-mark.png")
    if os.path.exists(logo_path):
        logo = Image.open(logo_path).convert("RGBA").resize((88, 88), Image.LANCZOS)
        bg.paste(logo, (W - 88 - 36, H - 88 - 36), logo)
    os.makedirs(SHARE_DIR, exist_ok=True)
    bg.save(os.path.join(SHARE_DIR, f"{p['id']}.jpg"), "JPEG", quality=84, optimize=True, progressive=True)
    return f"images/share/{p['id']}.jpg"


# ---------------------------------------------------------------- head helpers

def set_meta(doc, attr, key, value):
    """Replace the content of <meta {attr}="{key}" ...>, or add it before </head>."""
    pattern = re.compile(r'<meta %s="%s" content="[^"]*"\s*/?>' % (attr, re.escape(key)))
    tag = f'<meta {attr}="{key}" content="{esc(value)}" />'
    if pattern.search(doc):
        return pattern.sub(lambda _m: tag, doc, count=1)
    return doc.replace("</head>", f"  {tag}\n</head>", 1)


def set_head(doc, title, description, url, image_url, og_type="website", image_size=None):
    doc = re.sub(r"<title>.*?</title>", lambda _m: f"<title>{esc(title)}</title>", doc, count=1)
    doc = re.sub(r'\s*<link rel="canonical"[^>]*>', "", doc)
    doc = re.sub(r'\s*<meta name="robots"[^>]*>', "", doc)
    og_title = title.replace(f" | {STORE}", "")
    for attr, key, value in [
        ("name", "description", description),
        ("property", "og:title", og_title),
        ("property", "og:description", description),
        ("property", "og:type", og_type),
        ("property", "og:site_name", STORE),
        ("property", "og:url", url),
        ("property", "og:image", image_url),
        ("name", "twitter:card", "summary_large_image"),
        ("name", "twitter:title", og_title),
        ("name", "twitter:description", description),
        ("name", "twitter:image", image_url),
    ]:
        doc = set_meta(doc, attr, key, value)
    if image_size:
        doc = set_meta(doc, "property", "og:image:width", str(image_size[0]))
        doc = set_meta(doc, "property", "og:image:height", str(image_size[1]))
    return doc.replace("</head>", f'  <link rel="canonical" href="{url}" />\n</head>', 1)


def breadcrumb_ld(items):
    return {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": n + 1, "name": name, "item": url}
            for n, (name, url) in enumerate(items)
        ],
    }


