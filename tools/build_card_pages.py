#!/usr/bin/env python3
"""Build the site's generated, search-optimised pages from products.js.

WhatsApp, Instagram, Facebook and search engines read a page's HTML and <meta>
tags, so everything that should be found or shared is written out as real HTML
here rather than filled in by JavaScript. For each run this writes:

  card-<id>.html            one page per card, built from product.html, with a
                            unique SEO title and description, "About this card"
                            copy, breadcrumbs, internal links and Product data
  images/share/<id>.jpg     a 1200x630 link-preview image per card
  <category>.html           landing pages (PSA graded, PSA 10, Japanese, eras,
                            Pokémon...) for every category with enough stock,
                            configured in seo/categories.json
  pokemon-tcg-sets.html     every Pokémon TCG era and set, from seo/sets.json
  card-pages.js             the list of card pages, so the site links to them
  sitemap.xml               every indexable page, with card photos
  google-merchant-feed.xml  in-stock cards for free Google Shopping listings
It also refreshes the "shop by" links on the home page and in every footer
(between <!-- seo:... --> markers). Product names and checkout are never touched.

Run after changing products.js, product.html, seo/*.json or a card photo:
    python3 tools/build_card_pages.py
then check the result with:
    python3 tools/seo_audit.py
The "Card share pages" GitHub Action runs both on every relevant push to main.
Needs node (to read products.js) and Pillow.
"""
