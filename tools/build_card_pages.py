def footer_block(pages):
    wanted = ["psa", "psa-10", "ace", "japanese", "english"]
    by_id = {pg["id"]: pg for pg in pages}
    items = [(by_id[k]["file"], by_id[k]["link_text"].replace(" Pokémon", "")) for k in wanted if k in by_id]
    items.append((GUIDE_FILE, "Pokémon sets in order"))
    lis = "".join(f'<li><a href="{f}">{esc(t[0].upper() + t[1:])}</a></li>' for f, t in items)
    return (f'<!-- seo:footer-links --><nav class="footer-shop" aria-label="Shop by category">'
            f'<ul class="footer-links">{lis}</ul></nav>'
            f'<p class="footer-trader">{esc(TRADER)}</p><!-- /seo:footer-links -->')


def fill_markers(files, name, block):
    pattern = re.compile(r"<!-- seo:%s -->[\s\S]*?<!-- /seo:%s -->" % (name, name))
    for rel in files:
        doc = read(rel)
        if pattern.search(doc):
            write(rel, pattern.sub(lambda _m: block, doc, count=1))


