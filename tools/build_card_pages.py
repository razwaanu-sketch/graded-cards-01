def primary_category(product, pages):
    """The page a card's breadcrumb points to: its era, else its grader."""
    for kind, key in (("era", None), ("fixed", "psa"), ("fixed", "ace")):
        for pg in pages:
            if pg["kind"] == kind and (key is None or pg["id"] == key) and any(c["id"] == product["id"] for c in pg["cards"]):
                return pg
    return None


